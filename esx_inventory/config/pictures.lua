-- ================================================================= --
-- Generic fallback so a missing icon never renders blank in-game.
-- Every `Config.Pictures[name]` read anywhere in this resource (client
-- AND server, every call site) goes through this same table, so a
-- metatable here covers all of them for free - no need to touch every
-- individual read site.
--   * WEAPON_* with no specific entry above -> the pack's own generic
--     weapon icon (already bundled, src/html/assets/images/items/wpn_generic.png)
--   * anything else -> a small inline SVG "?" box (a data: URI, drawn
--     by this file itself - not an external download, so nothing to
--     go stale or violate copyright on)
-- ================================================================= --
local GENERIC_WEAPON_ICON = 'nui://esx_inventory/src/html/assets/images/items/wpn_generic.png'
local GENERIC_ITEM_ICON = 'data:image/svg+xml,%3Csvg xmlns=\'http://www.w3.org/2000/svg\' viewBox=\'0 0 64 64\'%3E%3Crect x=\'4\' y=\'4\' width=\'56\' height=\'56\' rx=\'8\' fill=\'%23222222\' stroke=\'%23888888\' stroke-width=\'2\'/%3E%3Ctext x=\'32\' y=\'42\' font-size=\'28\' font-family=\'sans-serif\' fill=\'%23888888\' text-anchor=\'middle\'%3E%3F%3C/text%3E%3C/svg%3E'

setmetatable(Config.Pictures, {
    __index = function(_, key)
        if type(key) == 'string' and key:sub(1, 7) == 'WEAPON_' then
            return GENERIC_WEAPON_ICON
        end
        return GENERIC_ITEM_ICON
    end
})

