    },
}
local num = 1
local time = 300

function send()
    local data = announce[num]
    if data then
        TriggerEvent('chat:addMessage', {
            template = temp[data.template].template,
            args = data.args
        })
     end
    num = num + 1
    if num > #announce then
        num = 1
    end
    time = (ESX.GetPlayerData().SelfLevel or 1) * 120
    Citizen.SetTimeout(time * 1000,send)
end

Citizen.SetTimeout(5 * 60000,send)
